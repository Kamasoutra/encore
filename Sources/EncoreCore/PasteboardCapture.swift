import AppKit

public enum PasteboardCapture {
    public static let ignoredTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "org.nspasteboard.privacy"]
    public static let maxBytes = 25 * 1_048_576

    public static func read(_ pasteboard: NSPasteboard, sourceName: String, sourceBundle: String, ignoreSensitive: Bool = true) throws -> (clip: Clip, payload: ClipPayload)? {
        let count = pasteboard.changeCount
        let types = (pasteboard.types ?? []).map(\.rawValue)
        if ignoreSensitive && ignoredTypes.contains(where: types.contains) { return nil }
        guard let sourceItems = pasteboard.pasteboardItems, !sourceItems.isEmpty else { return nil }
        var bytes = 0
        var items: [PasteItem] = []
        for source in sourceItems {
            if ignoreSensitive && ignoredTypes.contains(where: { source.types.map(\.rawValue).contains($0) }) { return nil }
            var representations: [String: Data] = [:]
            for type in source.types {
                guard !type.rawValue.hasPrefix("com.apple.pasteboard.promised"), !type.rawValue.lowercased().contains("filepromise") else { continue }
                guard let data = source.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= maxBytes else { throw CaptureError.tooLarge }
                representations[type.rawValue] = data
            }
            if !representations.isEmpty { items.append(.init(representations)) }
        }
        guard !items.isEmpty else { return nil }
        let payload = ClipPayload(items: items)
        var text = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL) ?? ""
        if text.isEmpty, let rtf = pasteboard.data(forType: .rtf), let attributed = NSAttributedString(rtf: rtf, documentAttributes: nil) { text = attributed.string }
        let files = sourceItems.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }
        let hasImage = types.contains { [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue, "public.jpeg", "public.heic"].contains($0) }
        guard pasteboard.changeCount == count, !text.isEmpty || !files.isEmpty || hasImage else { return nil }
        let kind = ClipKind.detect(text: text, hasImage: hasImage, hasFiles: !files.isEmpty)
        return (Clip(fingerprint: payload.fingerprint, kind: kind, text: text, sourceName: sourceName, sourceBundle: sourceBundle, byteCount: bytes, fileNames: files.map(\.lastPathComponent)), payload)
    }

    public enum CaptureError: LocalizedError {
        case tooLarge
        public var errorDescription: String? { "Élément ignoré : limite de 25 Mo par copie." }
    }
}
